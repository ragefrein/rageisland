export function roundedPixels(pixbuf) {
    const {width, height} = pixbuf;
    const channels = pixbuf.get_n_channels();
    const stride = pixbuf.get_rowstride();
    const pixels = pixbuf.get_pixels();
    const output = new Uint8Array(width * height * 4);
    const radius = Math.min(width, height) * 0.16;
    for (let y = 0; y < height; y++) {
        for (let x = 0; x < width; x++) {
            const source = y * stride + x * channels;
            const target = (y * width + x) * 4;
            const dx = Math.max(0, radius - Math.min(x + 0.5, width - x - 0.5));
            const dy = Math.max(0, radius - Math.min(y + 0.5, height - y - 0.5));
            const coverage = Math.max(0, Math.min(1, radius + 0.5 - Math.hypot(dx, dy)));
            output[target] = pixels[source];
            output[target + 1] = pixels[source + 1];
            output[target + 2] = pixels[source + 2];
            output[target + 3] = Math.round(coverage * (channels === 4 ? pixels[source + 3] : 255));
        }
    }
    return output;
}

export function parseLyrics(source) {
    const offset = Number(source.match(/\[offset:\s*([+-]?\d+)\]/i)?.[1] ?? 0) / 1000;
    const lines = [];
    for (const line of source.split(/\r?\n/)) {
        const marks = [...line.matchAll(/\[(\d+):(\d{2})(?:[.:](\d{1,3}))?\]/g)];
        if (!marks.length)
            continue;
        const last = marks[marks.length - 1];
        const text = line.slice(last.index + last[0].length).trim();
        for (const [, minutes, seconds, fraction] of marks) {
            const time = Number(minutes) * 60 + Number(seconds) + Number(`0.${fraction ?? '0'}`);
            lines.push({time: time - offset, text});
        }
    }
    return lines.sort((a, b) => a.time - b.time);
}

export function lyricAt(lines, position) {
    let low = 0;
    let high = lines.length;
    while (low < high) {
        const mid = Math.floor((low + high) / 2);
        if (lines[mid].time <= position)
            low = mid + 1;
        else
            high = mid;
    }
    return low - 1;
}

